class SubjectTemplate {
  final String category;
  final String cluster;
  final String name;
  final int ww;
  final int pt;
  final int ex;
  final int termsTaught;
  final String termBlock;
  final double st1Weight;
  final double st2Weight;
  final double teWeight;

  const SubjectTemplate({
    required this.category,
    this.cluster = '',
    required this.name,
    required this.ww,
    required this.pt,
    required this.ex,
    this.termsTaught = 1,
    this.termBlock = 'FIRST TERM',
    this.st1Weight = 30,
    this.st2Weight = 30,
    this.teWeight = 40,
  });

  bool get isNoExam => ex == 0;

  String get weightSummary => isNoExam
      ? 'WW $ww% · PT $pt% · NO EXAM'
      : 'WW $ww% · PT $pt% · EX $ex%';

  String get termsSummary {
    if (termsTaught == 3) return '3 Terms (Full Year)';
    if (termsTaught == 2) return '2 Terms ($termBlock)';
    return '1 Term';
  }
}

