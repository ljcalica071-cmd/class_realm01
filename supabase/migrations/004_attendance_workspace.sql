CREATE TABLE IF NOT EXISTS public.attendance_record_edits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_record_id uuid NOT NULL
        REFERENCES public.attendance_records(id) ON DELETE RESTRICT,
    old_status text NOT NULL
        CHECK (old_status IN ('present', 'late', 'absent', 'excused')),
    new_status text NOT NULL
        CHECK (new_status IN ('present', 'late', 'absent', 'excused')),
    reason text NOT NULL
        CHECK (pg_catalog.length(pg_catalog.btrim(reason)) > 0),
    edited_by character varying NOT NULL
        REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at timestamp with time zone NOT NULL DEFAULT pg_catalog.now()
);

CREATE INDEX IF NOT EXISTS attendance_record_edits_record_created_id_idx
    ON public.attendance_record_edits
    (attendance_record_id, created_at DESC, id DESC);

