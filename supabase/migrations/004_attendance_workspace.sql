CREATE OR REPLACE FUNCTION public.attendance_workspace_student_summary(
    p_student_id text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_present_count bigint;
    v_total_days bigint;
    v_presence_rate numeric;
BEGIN
    IF p_student_id IS NULL OR pg_catalog.btrim(p_student_id) = '' THEN
        RAISE EXCEPTION 'Invalid student ID.'
            USING ERRCODE = '22023';
    END IF;

    PERFORM 1
    FROM public.users AS u
    WHERE u.id = p_student_id
      AND u.role = 'student';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Student was not found.'
            USING ERRCODE = '42501';
    END IF;

    SELECT
        pg_catalog.count(*) FILTER (WHERE status = 'present')::bigint,
        pg_catalog.count(*)::bigint
    INTO v_present_count, v_total_days
    FROM public.attendance_records
    WHERE student_id = p_student_id;

    IF v_total_days = 0 THEN
        v_presence_rate := 0.0;
    ELSE
        v_presence_rate := pg_catalog.round(
            v_present_count::numeric / v_total_days,
            4
        );
    END IF;

    RETURN pg_catalog.jsonb_build_object(
        'student_id', p_student_id,
        'present_count', v_present_count,
        'total_days', v_total_days,
        'presence_rate', v_presence_rate
    );
END;
$function$;

