-- Preserve the daily upsert key needed by idempotent batch writes. If the
-- equivalent unique index already exists, leave it untouched; duplicate legacy
-- rows make index creation fail rather than being rewritten or discarded.
DO $migration$
DECLARE
    v_student_attnum smallint;
    v_offering_attnum smallint;
    v_date_attnum smallint;
BEGIN
    SELECT attnum INTO STRICT v_student_attnum
    FROM pg_catalog.pg_attribute
    WHERE attrelid = 'public.attendance_records'::regclass
      AND attname = 'student_id'
      AND NOT attisdropped;

    SELECT attnum INTO STRICT v_offering_attnum
    FROM pg_catalog.pg_attribute
    WHERE attrelid = 'public.attendance_records'::regclass
      AND attname = 'subject_offering_id'
      AND NOT attisdropped;

    SELECT attnum INTO STRICT v_date_attnum
    FROM pg_catalog.pg_attribute
    WHERE attrelid = 'public.attendance_records'::regclass
      AND attname = 'attendance_date'
      AND NOT attisdropped;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_catalog.pg_index AS i
        JOIN pg_catalog.pg_class AS idx ON idx.oid = i.indexrelid
        JOIN pg_catalog.pg_am AS am ON am.oid = idx.relam
        WHERE i.indrelid = 'public.attendance_records'::regclass
          AND i.indisunique
          AND i.indisvalid
          AND i.indpred IS NULL
          AND i.indexprs IS NULL
          AND am.amname = 'btree'
          AND i.indnkeyatts = 3
          AND i.indkey[0] = v_student_attnum
          AND i.indkey[1] = v_offering_attnum
          AND i.indkey[2] = v_date_attnum
    ) THEN
        CREATE UNIQUE INDEX attendance_records_student_offering_date_uidx
            ON public.attendance_records
            USING btree (student_id, subject_offering_id, attendance_date);
    END IF;
END;
$migration$;

