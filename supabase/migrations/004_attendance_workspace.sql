CREATE OR REPLACE FUNCTION public.attendance_workspace_correct_record(
    p_teacher_id text,
    p_subject_offering_id uuid,
    p_attendance_record_id uuid,
    p_new_status text,
    p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_old_status text;
    v_modified_at timestamp with time zone;
BEGIN
    IF p_teacher_id IS NULL OR pg_catalog.btrim(p_teacher_id) = ''
       OR p_subject_offering_id IS NULL
       OR p_attendance_record_id IS NULL
       OR p_new_status IS NULL
       OR p_new_status NOT IN ('present', 'late', 'absent', 'excused')
       OR p_reason IS NULL
       OR pg_catalog.btrim(p_reason) = '' THEN
        RAISE EXCEPTION 'Invalid attendance correction input.'
            USING ERRCODE = '22023';
    END IF;

    -- The caller must supply the Firebase UID already verified by the Edge
    -- Function; this check also enforces the matching teacher/offering scope.
    PERFORM 1
    FROM public.users AS u
    JOIN public.subject_offerings AS so ON so.teacher_id = u.id
    WHERE u.id = p_teacher_id
      AND u.role = 'teacher'
      AND so.id = p_subject_offering_id
    FOR SHARE OF u, so;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Teacher is not authorized for this offering.'
            USING ERRCODE = '42501';
    END IF;

    SELECT ar.status
    INTO v_old_status
    FROM public.attendance_records AS ar
    WHERE ar.id = p_attendance_record_id
      AND ar.subject_offering_id = p_subject_offering_id
    FOR UPDATE OF ar;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Attendance record was not found for this offering.'
            USING ERRCODE = 'P0002';
    END IF;

    v_modified_at := pg_catalog.clock_timestamp();

    -- Do not rewrite recorded_by, source, student, offering, date, or remarks.
    UPDATE public.attendance_records
    SET status = p_new_status,
        modified_by = p_teacher_id,
        modified_at = v_modified_at
    WHERE id = p_attendance_record_id
      AND subject_offering_id = p_subject_offering_id;

    INSERT INTO public.attendance_record_edits (
        attendance_record_id,
        old_status,
        new_status,
        reason,
        edited_by
    ) VALUES (
        p_attendance_record_id,
        v_old_status,
        p_new_status,
        pg_catalog.btrim(p_reason),
        p_teacher_id
    );

    RETURN pg_catalog.jsonb_build_object(
        'attendance_record_id', p_attendance_record_id,
        'old_status', v_old_status,
        'new_status', p_new_status,
        'modified_by', p_teacher_id,
        'modified_at', v_modified_at
    );
END;
$function$;

REVOKE ALL ON FUNCTION public.attendance_workspace_correct_record(
    text, uuid, uuid, text, text
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.attendance_workspace_correct_record(
    text, uuid, uuid, text, text
) TO service_role;

CREATE OR REPLACE FUNCTION public.attendance_workspace_analytics(
    p_teacher_id text,
    p_subject_offering_id uuid,
    p_start_date date,
    p_end_date date
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_range_days integer;
    v_bucket_unit text;
    v_bucket_interval interval;
    v_result jsonb;
BEGIN
    IF p_teacher_id IS NULL OR pg_catalog.btrim(p_teacher_id) = ''
       OR p_subject_offering_id IS NULL
       OR p_start_date IS NULL
       OR p_end_date IS NULL
       OR p_start_date > p_end_date THEN
        RAISE EXCEPTION 'Invalid attendance analytics bounds.'
            USING ERRCODE = '22023';
    END IF;

    v_range_days := p_end_date - p_start_date + 1;
    IF v_range_days > 3660 THEN
        RAISE EXCEPTION 'Attendance analytics range cannot exceed 3660 days.'
            USING ERRCODE = '22023';
    END IF;

    PERFORM 1
    FROM public.users AS u
    JOIN public.subject_offerings AS so ON so.teacher_id = u.id
    WHERE u.id = p_teacher_id
      AND u.role = 'teacher'
      AND so.id = p_subject_offering_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Teacher is not authorized for this offering.'
            USING ERRCODE = '42501';
    END IF;

    IF v_range_days <= 31 THEN
        v_bucket_unit := 'day';
        v_bucket_interval := interval '1 day';
    ELSIF v_range_days <= 180 THEN
        v_bucket_unit := 'week';
        v_bucket_interval := interval '1 week';
    ELSE
        v_bucket_unit := 'month';
        v_bucket_interval := interval '1 month';
    END IF;

    WITH attendance_in_range AS MATERIALIZED (
        SELECT ar.student_id, ar.attendance_date, ar.status
        FROM public.attendance_records AS ar
        WHERE ar.subject_offering_id = p_subject_offering_id
          AND ar.attendance_date >= p_start_date
          AND ar.attendance_date <= p_end_date
    ),
    status_totals AS (
        SELECT
            pg_catalog.count(*) FILTER (WHERE status = 'present')::bigint AS present_count,
            pg_catalog.count(*) FILTER (WHERE status = 'late')::bigint AS late_count,
            pg_catalog.count(*) FILTER (WHERE status = 'absent')::bigint AS absent_count,
            pg_catalog.count(*) FILTER (WHERE status = 'excused')::bigint AS excused_count
        FROM attendance_in_range
    ),
    trend_data AS (
        SELECT
            CASE
                WHEN v_bucket_unit = 'day' THEN attendance_date
                ELSE pg_catalog.date_trunc(
                    v_bucket_unit,
                    attendance_date::timestamp without time zone
                )::date
            END AS bucket_start,
            pg_catalog.count(*) FILTER (
                WHERE status IN ('present', 'late')
            )::bigint AS present_count,
            pg_catalog.count(*) FILTER (
                WHERE status IN ('absent', 'excused')
            )::bigint AS absent_or_excused_count
        FROM attendance_in_range
        GROUP BY 1
    ),
    bucket_series AS (
        SELECT pg_catalog.generate_series(
            pg_catalog.date_trunc(
                v_bucket_unit,
                p_start_date::timestamp without time zone
            ),
            pg_catalog.date_trunc(
                v_bucket_unit,
                p_end_date::timestamp without time zone
            ),
            v_bucket_interval
        )::date AS bucket_start
    ),
    trend_summary AS (
        SELECT COALESCE(
            pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                    'bucket_start', b.bucket_start,
                    'present_count', COALESCE(t.present_count, 0),
                    'absent_or_excused_count',
                        COALESCE(t.absent_or_excused_count, 0)
                ) ORDER BY b.bucket_start
            ),
            '[]'::jsonb
        ) AS trend_points
        FROM bucket_series AS b
        LEFT JOIN trend_data AS t USING (bucket_start)
    ),
    at_risk_counts AS (
        SELECT student_id, pg_catalog.count(*)::bigint AS absence_count
        FROM attendance_in_range
        WHERE status = 'absent'
        GROUP BY student_id
        HAVING pg_catalog.count(*) >= 3
    ),
    at_risk_rows AS (
        SELECT
            r.student_id,
            r.absence_count,
            sp.first_name,
            sp.middle_name,
            sp.last_name,
            sec.section_name
        FROM at_risk_counts AS r
        LEFT JOIN public.student_profiles AS sp
            ON sp.student_id = r.student_id
        LEFT JOIN public.subject_offerings AS so
            ON so.id = p_subject_offering_id
        LEFT JOIN public.sections AS sec
            ON sec.id = so.section_id
    ),
    at_risk_summary AS (
        SELECT
            pg_catalog.count(*)::bigint AS warning_count,
            COALESCE(
                pg_catalog.jsonb_agg(
                    pg_catalog.jsonb_build_object(
                        'student_id', student_id,
                        'student_name', COALESCE(
                            NULLIF(
                                pg_catalog.concat_ws(
                                    ' ',
                                    CASE
                                        WHEN NULLIF(pg_catalog.btrim(last_name), '') IS NULL
                                            THEN NULL
                                        ELSE pg_catalog.btrim(last_name) || ','
                                    END,
                                    NULLIF(pg_catalog.btrim(first_name), ''),
                                    CASE
                                        WHEN NULLIF(pg_catalog.btrim(middle_name), '') IS NULL
                                            THEN NULL
                                        ELSE pg_catalog.left(pg_catalog.btrim(middle_name), 1) || '.'
                                    END
                                ),
                                ''
                            ),
                            student_id
                        ),
                        'section', COALESCE(section_name, ''),
                        'absence_count', absence_count
                    ) ORDER BY last_name NULLS LAST,
                               first_name NULLS LAST,
                               middle_name NULLS LAST,
                               student_id
                ),
                '[]'::jsonb
            ) AS at_risk_students
        FROM at_risk_rows
    )
    SELECT pg_catalog.jsonb_build_object(
        'subject_offering_id', p_subject_offering_id,
        'start_date', p_start_date,
        'end_date', p_end_date,
        'bucket_unit', v_bucket_unit,
        'present_count', s.present_count,
        'late_count', s.late_count,
        'absent_count', s.absent_count,
        'excused_count', s.excused_count,
        'presence_rate', CASE
            WHEN s.present_count + s.late_count + s.absent_count = 0 THEN NULL
            ELSE pg_catalog.round(
                (s.present_count + s.late_count)::numeric
                / (s.present_count + s.late_count + s.absent_count),
                4
            )
        END,
        'absences_and_excuses', s.absent_count + s.excused_count,
        'warning_count', r.warning_count,
        'trend_points', t.trend_points,
        'at_risk_students', r.at_risk_students
    )
    INTO v_result
    FROM status_totals AS s
    CROSS JOIN trend_summary AS t
    CROSS JOIN at_risk_summary AS r;

    RETURN v_result;
END;
$function$;

REVOKE ALL ON FUNCTION public.attendance_workspace_analytics(
